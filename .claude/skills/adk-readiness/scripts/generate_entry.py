def build_latest_json_single(result, stack, evaluator_skill, mode, module_key, is_this_run=True):
    base = {
        "evaluator": _safe_get(result, "evaluator", stack or "unknown"),
        "evaluator_skill": evaluator_skill,
        "evaluator_version": _safe_get(result, "version", "unknown"),
        "stack": stack,
        "mode": mode,
        "is_this_run": is_this_run,
        "timestamp": _safe_get(result, "timestamp") or datetime.now().isoformat(),
        "score": _safe_get(result, "score"),
        "level": _safe_get(result, "level"),
        "summary": _safe_get(result, "summary"),
        "report_path": _safe_get(result, "reportPath"),
        "data_path": _safe_get(result, "dataPath"),
        "module_key": module_key,
        "modules": None,
    }
    return base


def build_latest_json_multi(modules):
    mod_entries = []
    latest_ts = None
    for m in modules:
        result = m["result"]
        ts = _safe_get(result, "timestamp")
        if ts:
            try:
                dt = datetime.fromisoformat(str(ts).replace("Z", "+00:00"))
                if latest_ts is None or dt > latest_ts[0]:
                    latest_ts = (dt, ts)
            except ValueError:
                pass
        mod_entries.append({
            "module_key": m["module_key"],
            "stack": m["stack"],
            "evaluator": _safe_get(result, "evaluator", m["stack"] or "unknown"),
            "evaluator_skill": m["evaluator_skill"],
            "mode": m["mode"],
            "is_this_run": bool(m.get("is_this_run", True)),
            "timestamp": _safe_get(result, "timestamp"),
            "score": _safe_get(result, "score"),
            "level": _safe_get(result, "level"),
            "summary": _safe_get(result, "summary"),
            "report_path": _safe_get(result, "reportPath"),
        })

    return {
        "modules": mod_entries,
        "timestamp": (latest_ts[1] if latest_ts else None) or datetime.now().isoformat(),
    }


