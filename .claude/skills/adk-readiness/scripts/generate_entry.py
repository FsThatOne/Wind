def _parse_module_spec(spec):
    """Parse --module k=v,k=v,... into a dict with absolute result path.

    Required fields: stack, evaluator, key, result.
    Optional: mode (default 'deep'), this_run (0/1, default 0 = historical).
    """
    fields = {}
    for part in spec.split(","):
        if "=" not in part:
            continue
        k, v = part.split("=", 1)
        fields[k.strip()] = v.strip()

    required = ("stack", "evaluator", "key", "result")
    missing = [r for r in required if r not in fields]
    if missing:
        raise argparse.ArgumentTypeError(
            f"--module missing fields: {missing}. "
            f"Expected: stack=...,evaluator=...,key=...,result=...[,mode=...,this_run=0|1]"
        )

    result_path = fields["result"]
    if not os.path.isabs(result_path):
        result_path = os.path.abspath(result_path)

    mode = fields.get("mode", "deep")
    raw_this = fields.get("this_run", "0")
    is_this_run = str(raw_this).lower() in ("1", "true", "yes", "y", "on")

    return {
        "stack": fields["stack"],
        "evaluator_skill": fields["evaluator"],
        "module_key": fields["key"],
        "result_path": result_path,
        "mode": mode,
        "is_this_run": is_this_run,
    }


def _load_result(path):
    if not os.path.isfile(path):
        print(f"Error: result JSON not found: {path}", file=sys.stderr)
        sys.exit(1)
    with open(path, "r") as f:
        return json.load(f)


def main():
    parser = argparse.ArgumentParser(description="Generate adk-readiness entry page")
    parser.add_argument("--output-dir", required=True, help=".ai-readiness directory path")
    parser.add_argument("--language", default="zh", help="Report language (zh/en)")

    # Single-module flags
    parser.add_argument("--result-json", help="(single) Path to _evaluator_result.json")
    parser.add_argument("--stack", help="(single) Detected tech stack ID")
    parser.add_argument("--evaluator-skill", help="(single) Evaluator skill name")
    parser.add_argument("--module-key", help="(single) Module key used as details subdir name")
    parser.add_argument("--mode", default="deep", help="(single) Evaluation mode (quick/deep)")
    parser.add_argument(
        "--is-this-run",
        dest="is_this_run",
        default="true",
        help="(single) Whether this module was evaluated in this run (true/false, default true)",
    )

    # Multi-module flag (repeatable)
    parser.add_argument(
        "--module",
        action="append",
        default=[],
        type=_parse_module_spec,
        help="Multi-module entry. stack=<sid>,evaluator=<skill>,key=<moduleKey>,result=<absPath>[,mode=<quick|deep>][,this_run=0|1]. May be repeated.",
    )

    args = parser.parse_args()

    language = args.language if args.language in ("zh", "en") else "zh"
    single_is_this_run = str(args.is_this_run).lower() in ("1", "true", "yes", "y", "on")

    has_multi = bool(args.module)
    has_single = bool(args.result_json)

    if not has_multi and not has_single:
        print(
            "Error: either provide single-module flags (--result-json + --stack + ...) "
            "or at least one --module spec.",
            file=sys.stderr,
        )
        sys.exit(1)

    os.makedirs(args.output_dir, exist_ok=True)

    if has_multi:
        modules = []
        for spec in args.module:
            result = _load_result(spec["result_path"])
            modules.append({
                "stack": spec["stack"],
                "evaluator_skill": spec["evaluator_skill"],
                "module_key": spec["module_key"],
                "mode": spec["mode"],
                "result": result,
                "is_this_run": spec["is_this_run"],
            })
        md_content = render_multi_module(modules, language)
        json_content = build_latest_json_multi(modules)
    else:
        # Single mode
        for name, value in (
            ("--stack", args.stack),
            ("--evaluator-skill", args.evaluator_skill),
            ("--module-key", args.module_key),
        ):
            if not value:
                print(f"Error: single mode requires {name}", file=sys.stderr)
                sys.exit(1)

        result = _load_result(args.result_json)
        md_content = render_single_module(
            result,
            args.stack,
            args.evaluator_skill,
            args.mode,
            args.module_key,
            language,
            is_this_run=single_is_this_run,
        )
        json_content = build_latest_json_single(
            result,
            args.stack,
            args.evaluator_skill,
            args.mode,
            args.module_key,
            is_this_run=single_is_this_run,
        )

    md_path = os.path.join(args.output_dir, "latest.md")
    with open(md_path, "w") as f:
        f.write(md_content)
    print(f"Generated: {md_path}")

    json_path = os.path.join(args.output_dir, "latest.json")
    with open(json_path, "w") as f:
        json.dump(json_content, f, indent=2, ensure_ascii=False)
    print(f"Generated: {json_path}")


if __name__ == "__main__":
    main()
